/* A profile's social channels (YouTube, Instagram, X…): recognise the platform, keep
   links safe to render, and format follower counts. Channel URLs are typed
   by applicants, so only http(s) addresses ever become clickable links. */

export type ChannelKind =
  | "youtube"
  | "instagram"
  | "facebook"
  | "x"
  | "linkedin"
  | "tiktok"
  | "threads"
  | "snapchat"
  | "spotify"
  | "web";

export type Channel = { platform: string; url: string; followers?: number | null };

export const CHANNEL_LABELS: Record<ChannelKind, string> = {
  youtube: "YouTube",
  instagram: "Instagram",
  facebook: "Facebook",
  x: "X (Twitter)",
  linkedin: "LinkedIn",
  tiktok: "TikTok",
  threads: "Threads",
  snapchat: "Snapchat",
  spotify: "Spotify",
  web: "Website",
};

const HOSTS: [RegExp, ChannelKind][] = [
  [/(^|\.)(youtube\.com|youtu\.be)$/, "youtube"],
  [/(^|\.)instagram\.com$/, "instagram"],
  [/(^|\.)(facebook\.com|fb\.com|fb\.me)$/, "facebook"],
  [/(^|\.)(x\.com|twitter\.com)$/, "x"],
  [/(^|\.)linkedin\.com$/, "linkedin"],
  [/(^|\.)tiktok\.com$/, "tiktok"],
  [/(^|\.)threads\.(net|com)$/, "threads"],
  [/(^|\.)snapchat\.com$/, "snapchat"],
  [/(^|\.)spotify\.com$/, "spotify"],
];

const NAMES: [RegExp, ChannelKind][] = [
  [/youtube/i, "youtube"],
  [/instagram|\big\b/i, "instagram"],
  [/facebook|\bfb\b/i, "facebook"],
  [/twitter|^x$|^x\s*\(/i, "x"],
  [/linkedin/i, "linkedin"],
  [/tiktok/i, "tiktok"],
  [/threads/i, "threads"],
  [/snapchat/i, "snapchat"],
  [/spotify/i, "spotify"],
];

/**
 * Normalise a typed channel address to an absolute http(s) URL, or null when
 * it isn't a web address (javascript:, data:, mailto:, garbage…). A bare
 * "youtube.com/@acme" gets https:// added.
 */
export function safeChannelUrl(input: string | null | undefined): string | null {
  const raw = String(input ?? "").trim();
  if (!raw || raw.length > 500) return null;
  const withScheme = /^[a-z][a-z0-9+.-]*:/i.test(raw) ? raw : `https://${raw.replace(/^\/+/, "")}`;
  try {
    const url = new URL(withScheme);
    if (url.protocol !== "https:" && url.protocol !== "http:") return null;
    if (!url.hostname.includes(".") || url.username || url.password) return null;
    return url.toString();
  } catch {
    return null;
  }
}

/**
 * Which platform a channel is on. A brand icon is a trust signal, so when
 * there is a link only its real host decides: typing "YouTube" next to a link
 * to some other site gets a plain website pill, never the YouTube mark. The
 * typed name is used only when there is no usable link at all.
 */
export function channelKind(platform: string, url: string): ChannelKind {
  const safe = safeChannelUrl(url);
  if (safe) {
    const host = channelHost(safe);
    for (const [re, kind] of HOSTS) if (re.test(host)) return kind;
    return "web";
  }
  for (const [re, kind] of NAMES) if (re.test(platform.trim())) return kind;
  return "web";
}

/** The link's real host, e.g. "twitch.tv", shown on website pills. */
export function channelHost(href: string): string {
  return new URL(href).hostname.toLowerCase().replace(/^(www|m)\./, "");
}

/** 220000 → "220K", 1800000 → "1.8M". */
export function compactCount(n: number | null | undefined): string {
  const v = Number(n) || 0;
  if (v <= 0) return "";
  return new Intl.NumberFormat("en", { notation: "compact", maximumFractionDigits: 1 }).format(v);
}

/** Read the JSON `channels` column defensively; drop entries without a safe link. */
export function parseChannels(json: unknown): (Channel & { href: string; kind: ChannelKind })[] {
  if (!Array.isArray(json)) return [];
  return json.flatMap((c) => {
    if (!c || typeof c !== "object") return [];
    const { platform, url, followers } = c as Record<string, unknown>;
    const href = safeChannelUrl(typeof url === "string" ? url : "");
    if (!href) return [];
    const name = typeof platform === "string" ? platform : "";
    return [{ platform: name, url: href, href, followers: typeof followers === "number" ? followers : null, kind: channelKind(name, href) }];
  });
}

